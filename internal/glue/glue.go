// Target selects the storage backend a generated wrangler.toml binds.
type Target string

const (
	TargetD1 Target = "d1" // D1 database, optimistic KV adapter (default)
	TargetDO Target = "do" // Durable Object with transactional storage
)

// WranglerToml renders a starter wrangler.toml for the D1 target.
func WranglerToml(name string, params []ir.HandlerParam) string {
	s, _ := WranglerTomlFor(name, params, TargetD1)
	return s
}

// WranglerTomlFor renders a starter wrangler.toml for a target.
func WranglerTomlFor(name string, params []ir.HandlerParam, target Target) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "name = %q\nmain = \"worker.js\"\ncompatibility_date = \"2026-09-01\"\n", name)
	b.WriteString("\n[vars]\n# How outbox entries are delivered after commit: \"fetch\" | \"log\" | \"queue\" (see docs/runtime.md)\nKEKKAI_OUTBOX = \"fetch\"\n")
	switch target {
	case TargetD1, "":
		for _, p := range params {
			if p.Kind == "Db" {
				fmt.Fprintf(&b, "\n[[d1_databases]]\nbinding = %q\ndatabase_name = %q\ndatabase_id = \"local\"\n",
					strings.ToUpper(p.Name), name+"-"+p.Name)
			}
		}
	case TargetDO:
		b.WriteString("# Which Durable Object a request is routed to: \"global\" | \"segment:N\" | \"header:NAME\" | \"query:NAME\"\nKEKKAI_DO_SHARD = \"global\"\n")
		b.WriteString("\n[[durable_objects.bindings]]\nname = \"KEKKAI_DO\"\nclass_name = \"KekkaiObject\"\n")
		b.WriteString("\n[[migrations]]\ntag = \"v1\"\nnew_sqlite_classes = [\"KekkaiObject\"]\n")
	default:
		return "", fmt.Errorf("unknown target %q (want d1 or do)", target)
	}
	return b.String(), nil
}

func jsKey(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}
