// Meta is the program metadata consumed by the runtime.
type Meta struct {
	Strings       []string          `json:"strings"`
	HandlerParams []ir.HandlerParam `json:"handlerParams"`
}

// MetaJS renders kekkai_meta.js.
func MetaJS(m Meta) string {
	if m.Strings == nil {
		m.Strings = []string{}
	}
	b, _ := json.MarshalIndent(m, "", "  ")
	return "// Generated by kek. Do not edit.\nexport default " + string(b) + ";\n"
}

// WorkerJS renders the Workers entry point. Capabilities are created from
// the environment (this is the only place where the program receives
// authority):
//
//   - a `&Db` parameter named `db` uses the D1 binding `DB` through the
//     optimistic key-value adapter (D1KvStore), or, when the Worker has a
//     Durable Object namespace bound as KEKKAI_DO, the storage of the
//     object the request is routed to (DurableObjectStore);
//   - `&Log` is the console, `&Net` is fetch, `&Clock` / `&Random` are the
//     system clock and crypto.getRandomValues.
//
// The outbox is selected with the KEKKAI_OUTBOX variable ("fetch",
// "log", or "queue" with a Queue producer bound as OUTBOX). See
// docs/runtime.md.
func WorkerJS(params []ir.HandlerParam) string {
	var b strings.Builder
	b.WriteString(workerHead)
	for _, p := range params {
		var expr string
		switch p.Kind {
		case "request":
			continue
		case "Db":
			expr = fmt.Sprintf("dbCap(db(%q), outbox(env))", strings.ToUpper(p.Name))
		case "Log":
			expr = "consoleLog()"
		case "Net":
			expr = "fetchNet()"
		case "Clock":
			expr = "systemClock()"
		case "Random":
			expr = "cryptoRandom()"
		default:
			continue
		}
		fmt.Fprintf(&b, "    %s: %s,\n", jsKey(p.Name), expr)
	}
	b.WriteString(workerTail)
	return b.String()
}

